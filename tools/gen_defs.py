"""Regenerates flightlog-core/src/tlog/defs.rs from pymavlink's all.xml dialect.

    pip install pymavlink==2.4.50
    python tools/gen_defs.py

Fields are listed in XML order (the order pymavlink's to_dict() and the
Arrow tables use) with their byte offset in the wire payload (MAVLink sorts
base fields by type size, extensions follow in XML order).
"""
import pathlib

import pymavlink
import pymavlink.dialects.v20.all as dialect

TYPES = {
    "uint8_t": ("U8", 1), "uint8_t_mavlink_version": ("U8", 1), "int8_t": ("I8", 1),
    "uint16_t": ("U16", 2), "int16_t": ("I16", 2),
    "uint32_t": ("U32", 4), "int32_t": ("I32", 4),
    "uint64_t": ("U64", 8), "int64_t": ("I64", 8),
    "float": ("F32", 4), "double": ("F64", 8), "char": ("Char", 1),
}

out = [
    "//! MAVLink message field layouts.",
    "//!",
    f"//! Generated by tools/gen_defs.py from pymavlink {pymavlink.__version__} (`all.xml` dialect).",
    "//! Do not edit by hand.",
    "",
    "use super::{FieldDef, MessageDef, Ty};",
    "",
    "/// Every message of the `all.xml` dialect, sorted by id.",
    "pub static MESSAGES: &[MessageDef] = &[",
]
count = 0
for msg_id in sorted(dialect.mavlink_map):
    cls = dialect.mavlink_map[msg_id]
    ordered = cls.ordered_fieldnames
    arr_by_wire = cls.array_lengths
    # wire offsets
    offsets = {}
    ofs = 0
    for w, name in enumerate(ordered):
        xml_i = cls.fieldnames.index(name)
        ty, size = TYPES[cls.fieldtypes[xml_i]]
        n = arr_by_wire[w] or 1
        offsets[name] = (ofs, ty, arr_by_wire[w], size)
        ofs += size * n
    assert ofs == cls.unpacker.size, (cls.msgname, ofs, cls.unpacker.size)
    fields = []
    units = getattr(cls, "fieldunits_by_name", {}) or {}
    for name in cls.fieldnames:
        o, ty, arr, _ = offsets[name]
        unit = units.get(name, "")
        fields.append(f'FieldDef {{ name: "{name}", ty: Ty::{ty}, array: {arr}, offset: {o}, unit: "{unit}" }}')
    out.append(f'    MessageDef {{ id: {msg_id}, name: "{cls.msgname}", len: {ofs}, fields: &[')
    for f in fields:
        out.append(f"        {f},")
    out.append("    ] },")
    count += 1
out.append("];")
path = pathlib.Path(__file__).resolve().parent.parent / "flightlog-core" / "src" / "tlog" / "defs.rs"
path.write_text("\n".join(out) + "\n", newline="\n")
print(count, "messages")
